import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const targetPath = resolve(rootDir, 'src/generated/buildInfo.ts');

function resolveGitDir() {
  const dotGitPath = resolve(rootDir, '.git');

  if (!existsSync(dotGitPath)) return null;

  if (statSync(dotGitPath).isDirectory()) {
    return dotGitPath;
  }

  const dotGitContents = readFileSync(dotGitPath, 'utf8').trim();
  const gitDirMatch = dotGitContents.match(/^gitdir: (.+)$/);

  if (!gitDirMatch) return null;

  return resolve(rootDir, gitDirMatch[1]);
}

function getLastCommitDate() {
  const gitDir = resolveGitDir();

  if (gitDir) {
    const headLogPath = resolve(gitDir, 'logs/HEAD');

    if (existsSync(headLogPath)) {
      const headLog = readFileSync(headLogPath, 'utf8').trim();
      const latestEntry = headLog.split('\n').filter(Boolean).at(-1);
      const timestampMatch = latestEntry?.match(/> (\d+) [+-]\d{4}\t/);

      if (timestampMatch) {
        return new Date(Number(timestampMatch[1]) * 1000).toISOString();
      }
    }
  }

  if (process.env.SOURCE_DATE_EPOCH) {
    return new Date(Number(process.env.SOURCE_DATE_EPOCH) * 1000).toISOString();
  }

  return new Date().toISOString();
}

const lastUpdatedAt = getLastCommitDate();

mkdirSync(dirname(targetPath), { recursive: true });
writeFileSync(
  targetPath,
  `// This file is generated by scripts/write-build-info.mjs. Do not edit.\nexport const lastUpdatedAt = ${JSON.stringify(lastUpdatedAt)};\n`,
);
